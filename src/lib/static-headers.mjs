// Static documents keep inline scripts and style attributes. Hashing the
// large offline page is outside this release, so script-src and style-src
// still allow 'unsafe-inline'. API responses use a separate, stricter policy.

export const SECURITY_HEADER_NAMES = [
  'Referrer-Policy',
  'X-Content-Type-Options',
  'X-Frame-Options',
  'Permissions-Policy',
  'Strict-Transport-Security',
  'Content-Security-Policy',
];

export const ONLINE_PATHS = ['/online', '/online/', '/online.html'];

const LOCAL_BRIDGE = [
  'ws://127.0.0.1:8765',
  'ws://localhost:8765',
  'http://127.0.0.1:8765',
  'http://localhost:8765',
];

export function contentSecurityPolicy(allowLocalBridge = false) {
  const connect = ["'self'", 'https://api.github.com', 'https://challenges.cloudflare.com'];
  if (allowLocalBridge) connect.push(...LOCAL_BRIDGE);
  return [
    "default-src 'self'",
    "script-src 'self' 'unsafe-inline' https://challenges.cloudflare.com https://cdn.jsdelivr.net",
    "style-src 'self' 'unsafe-inline'",
    "style-src-attr 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "font-src 'self' data:",
    `connect-src ${connect.join(' ')}`,
    "worker-src 'self'",
    "frame-src https://challenges.cloudflare.com",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; ');
}

export function headersForPath(pathname) {
  const headers = {
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    'X-Content-Type-Options': 'nosniff',
    'X-Frame-Options': 'DENY',
    'Permissions-Policy': 'camera=(), microphone=(), geolocation=()',
    'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
    'Content-Security-Policy': contentSecurityPolicy(ONLINE_PATHS.includes(pathname)),
  };
  if (pathname === '/version.json') headers['Cache-Control'] = 'no-store';
  return headers;
}

function patternMatches(pattern, pathname) {
  if (pattern === '/*') return pathname.startsWith('/');
  if (pattern.endsWith('/*')) return pathname.startsWith(pattern.slice(0, -1));
  return pattern === pathname;
}

export function applyHeaderFile(text, pathname) {
  const rules = [];
  let current = null;
  for (const line of text.split('\n')) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    if (line.startsWith(' ') || line.startsWith('\t')) {
      if (current) current.headers.push(line.trim());
      continue;
    }
    current = {pattern: line.trim(), headers: []};
    rules.push(current);
  }
  const headers = new Map();
  for (const rule of rules) {
    if (!patternMatches(rule.pattern, pathname)) continue;
    for (const entry of rule.headers) {
      if (entry.startsWith('! ')) {
        headers.delete(entry.slice(2).trim().toLowerCase());
        continue;
      }
      const separator = entry.indexOf(':');
      const name = entry.slice(0, separator).trim().toLowerCase();
      const value = entry.slice(separator + 1).trim();
      headers.set(name, headers.has(name) ? `${headers.get(name)}, ${value}` : value);
    }
  }
  return headers;
}

export function renderStaticHeaders() {
  const base = headersForPath('/');
  const onlinePolicy = headersForPath('/online')['Content-Security-Policy'];
  const lines = [
    '# Generated by scripts/render-static-headers.mjs. Do not edit by hand.',
    '# A later rule must detach Content-Security-Policy before replacing it.',
    '# Cloudflare joins repeated header values instead of replacing them.',
    '/*',
  ];
  for (const name of SECURITY_HEADER_NAMES) lines.push(`  ${name}: ${base[name]}`);
  lines.push('');
  for (const onlinePath of ONLINE_PATHS) {
    lines.push(onlinePath, '  ! Content-Security-Policy', `  Content-Security-Policy: ${onlinePolicy}`, '');
  }
  lines.push('/version.json', '  Cache-Control: no-store', '');
  return lines.join('\n');
}
